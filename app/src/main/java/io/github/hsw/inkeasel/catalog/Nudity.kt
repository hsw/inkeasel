package io.github.hsw.inkeasel.catalog

/**
 * How much nudity a catalog painting shows, ordered from least to most strict to hide. Stored as its
 * [ordinal] (`0`, `1`, `2`); a filter keeps the rows whose level is below [NudityFilter.nudityBelow].
 */
enum class NudityLevel {
    NONE,

    /** Nudity other than [EXPLICIT]: a classic nude. */
    NUDE,

    /** Genitals in focus, a sexual act or assault. */
    EXPLICIT,
}

/**
 * The Catalog's nudity filter, the setting's three values. [nudityBelow] is the exclusive bound on a row's
 * [NudityLevel] ordinal: a row shows when its level's ordinal is less than it.
 */
enum class NudityFilter(val nudityBelow: Int) {
    SHOW_ALL(NudityLevel.EXPLICIT.ordinal + 1),
    HIDE_EXPLICIT(NudityLevel.EXPLICIT.ordinal),
    HIDE_NUDES(NudityLevel.NUDE.ordinal),
    ;

    /** Whether a row of [level] shows under this filter. */
    fun shows(level: NudityLevel): Boolean = level.ordinal < nudityBelow

    companion object {
        val DEFAULT = HIDE_EXPLICIT

        /**
         * The filter in force: [HIDE_NUDES] while the device locks it (parental controls, a restricted
         * profile), else [choice].
         */
        fun effective(choice: NudityFilter, locked: Boolean): NudityFilter = if (locked) HIDE_NUDES else choice
    }
}

/**
 * Nudity of catalog paintings, pure. [EXPLICIT] and [NUDE] are the two levels of `tools/catalog-nsfw.txt`,
 * built in so they apply to the release already published: an import stores each row's [levelOf], each process
 * start raises stored rows to their listed level ([CatalogDao.markListed]), and the Catalog's filter
 * ([NudityFilter]) hides them by it; the starter set never carries an explicit one. A unit test checks both
 * sets against the file.
 */
object Nudity {
    /** Wikidata's "nude" genre (P136). */
    const val NUDE_GENRE = "Q40446"

    /**
     * A painting's level: the strictest of the release's `nsfw` field (`nude`, `explicit`; an unknown value is
     * ignored), the list's level for [id] (a bare `Q…` id) and the nude genre among [genres] ([NudityLevel.NUDE]).
     * Never less strict than any one source: an absent field cannot be told from "none".
     */
    fun levelOf(nsfw: String?, genres: List<String>, id: String): NudityLevel = maxOf(
        fromNsfw(nsfw),
        listed(id),
        if (NUDE_GENRE in genres) NudityLevel.NUDE else NudityLevel.NONE,
    )

    /** The level the list gives a bare `Q…` id; [NudityLevel.NONE] when it is not listed. */
    fun listed(id: String): NudityLevel = when (id) {
        in EXPLICIT -> NudityLevel.EXPLICIT
        in NUDE -> NudityLevel.NUDE
        else -> NudityLevel.NONE
    }

    fun isExplicit(wikidataId: String): Boolean = wikidataId in EXPLICIT

    /** A release `nsfw` value; absent or unknown is [NudityLevel.NONE]. */
    private fun fromNsfw(nsfw: String?): NudityLevel = when (nsfw) {
        "explicit" -> NudityLevel.EXPLICIT
        "nude" -> NudityLevel.NUDE
        else -> NudityLevel.NONE
    }

